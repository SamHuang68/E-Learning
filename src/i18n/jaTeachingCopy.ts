export function jaTeachingCopy(locale: UiLocale, text: string): string {
  if (locale !== 'en' || !text) return text
  if (!Object.hasOwn(JA_TEACHING_EN, text)) throw new Error('缺少日語教材英文翻譯：' + text)
  const translated = JA_TEACHING_EN[text]
  if (/[\u3400-\u9fff\uf900-\ufaff]/.test(translated)) throw new Error('日語教材英文翻譯含漢字：' + text)
  return translated
}

export function localizeJaPractice(pack: UnitPractice | null, locale: UiLocale): UnitPractice | null {
  if (!pack || locale !== 'en') return pack
  const localizeCards = (cards: UnitPractice['vocab']) => cards.map((card) => ({
    ...card,
    meaning: jaTeachingCopy(locale, card.meaning),
    sentenceZh: card.sentenceZh ? jaTeachingCopy(locale, card.sentenceZh) : undefined,
    scenario: jaTeachingCopy(locale, card.scenario),
  }))
  return { vocab: localizeCards(pack.vocab), passage: localizeCards(pack.passage), grammar: localizeCards(pack.grammar) }
}
