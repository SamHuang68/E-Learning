export const practiceThemeBanks: Record<string, PracticeThemeBank> = {
  ...Object.fromEntries(Object.entries(jaSeeds).map(([key, seed]) => [key, jaBank(seed)])),
  ...Object.fromEntries(
    Object.entries(toeicSeeds).map(([key, seed]) => [key, toeicBank(seed)]),
  ),
}

export function getPracticeThemeBank(key: string): PracticeThemeBank {
  const bank = practiceThemeBanks[key]
  if (bank) return bank
  if (key.includes(':')) {
    const [prefix] = key.split(':')
    if (prefix === 'orange' || prefix === 'green' || prefix === 'blue' || prefix === 'gold') {
      return toeicBank({
        title: 'TOEIC Practice',
        scenario: 'business',
        register: prefix === 'orange' ? 'polite' : 'business',
        terms: [],
        passageTopics: ['business notice', 'email request', 'meeting update', 'client call', 'schedule change', 'short announcement', 'office memo', 'travel plan', 'project review', 'service issue', 'training reminder', 'final review'],
      })
    }
  }
  return jaBank({
    title: '日本語練習',
    scenario: '練習',
    terms: [],
    passageTopics: ['短い会話', '予定の確認', '理由の説明', '丁寧な依頼', '読解練習', '聞き取り練習', '復習', 'まとめ'],
  })
}

export function getDefaultGrammar(
  key: string,
  scenario: string,
  register: PracticeRegister,
): Omit<SpeakableCard, 'id'>[] {
  const [prefix] = key.split(':')
  if (prefix === 'orange' || prefix === 'green' || prefix === 'blue' || prefix === 'gold') {
    return toeicGeneralGrammar(scenario, register)
  }
  return jaGeneralGrammar(scenario)
}
