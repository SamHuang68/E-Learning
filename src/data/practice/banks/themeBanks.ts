function parseTerm(raw: string): {
  head: string
  reading?: string
  meaning: string
} {
  const parts = raw.split('|')
  if (parts.length === 2) return { head: parts[0], meaning: parts[1] }
  return { head: parts[0], reading: parts[1], meaning: parts[2] }
}

function jaVocabCard(
  raw: string,
  bank: Pick<UnitSeed, 'title' | 'scenario' | 'register'>,
): Omit<SpeakableCard, 'id'> {
  const term = parseTerm(raw)
  return {
    ...term,
    sentence: `${bank.title}の場面で「${term.head}」を自然に使います。`,
    sentenceZh: `在「${bank.title}」情境中自然使用「${term.meaning}」。`,
    scenario: bank.scenario,
    register: bank.register ?? 'polite',
  }
}

function toeicVocabCard(
  raw: string,
  bank: Pick<UnitSeed, 'title' | 'scenario' | 'register'>,
): Omit<SpeakableCard, 'id'> {
  const term = parseTerm(raw)
  return {
    ...term,
    sentence: `In a ${bank.scenario} situation, "${term.head}" is a key word to listen for.`,
    sentenceZh: `在「${bank.title}」情境中，「${term.meaning}」是需要聽懂的關鍵字。`,
    scenario: bank.scenario,
    register: bank.register ?? 'polite',
  }
}

function jaBank(seed: UnitSeed): PracticeThemeBank {
  return {
    language: 'ja',
    title: seed.title,
    scenario: seed.scenario,
    register: seed.register ?? 'polite',
    vocab: [...seed.terms, ...sharedJaTerms].map((term) => jaVocabCard(term, seed)),
    passageTopics: seed.passageTopics,
    grammar: seed.grammar,
  }
}

function toeicBank(seed: UnitSeed): PracticeThemeBank {
  return {
    language: 'en',
    title: seed.title,
    scenario: seed.scenario,
    register: seed.register ?? 'polite',
    vocab: [...seed.terms, ...sharedToeicTerms].map((term) =>
      toeicVocabCard(term, seed),
    ),
    passageTopics: seed.passageTopics,
    grammar: seed.grammar,
  }
}

